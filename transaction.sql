-- BRANCH TOPPERS
SELECT NAME,BRANCH,MARKS FROM (SELECT *,FIRST_VALUE(NAME) OVER(PARTITION BY BRANCH ORDER BY MARKS DESC) AS 'TOPPER_NAME',
FIRST_VALUE(MARKS) OVER(PARTITION BY BRANCH ORDER BY MARKS DESC) AS 'TOPPER_MARKS'
FROM MARKS) T
WHERE T.NAME=T.TOPPER_NAME AND T.MARKS=T.TOPPER_MARKS;

SELECT NAME,BRANCH,MARKS FROM (SELECT *,LAST_VALUE(NAME) OVER(PARTITION BY BRANCH ORDER BY MARKS DESC ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING) AS 'TOPPER_NAME',
LAST_VALUE(MARKS) OVER(PARTITION BY BRANCH ORDER BY MARKS DESC ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING) AS 'TOPPER_MARKS'
FROM MARKS) T
WHERE T.NAME=T.TOPPER_NAME AND T.MARKS=T.TOPPER_MARKS;

SELECT *,LAG(MARKS) OVER(PARTITION BY BRANCH ORDER BY STUDENT_ID),
LEAD(MARKS) OVER(PARTITION BY BRANCH ORDER BY STUDENT_ID) FROM MARKS;

