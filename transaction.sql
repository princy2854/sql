-- TOP 2 MOST PAYING CUSTOMERS OF EACH MONTH
CREATE DATABASE ZOMATO;
USE ZOMATO;
SELECT * FROM (SELECT MONTH(DATE) AS MONTH_NUM,
       MONTHNAME(DATE) AS MONTH_NAME,
       USER_ID,
       SUM(AMOUNT) AS TOTAL,
       RANK() OVER(PARTITION BY MONTHNAME(DATE) ORDER BY SUM(AMOUNT) DESC) AS MONTH_RANK
FROM ORDERS
GROUP BY MONTHNAME(DATE),MONTH_NUM, USER_ID
ORDER BY MONTH_NUM) T 
WHERE T.MONTH_RANK<3
ORDER BY MONTH_NAME DESC, MONTH_RANK ASC;

