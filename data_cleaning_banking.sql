FROM TRANSACTIONS 
GROUP BY ACCOUNT_ID),
DISTRIBUTED AS(
SELECT *,NTILE(10) OVER(ORDER BY TOTAL_AMOUNT DESC) AS DISTRIBUTED_DATA FROM TOTAL_SPENDING
)
SELECT CATEGORY,COUNT(*) FROM (SELECT ACCOUNT_ID,TOTAL_AMOUNT,
CASE  
   WHEN DISTRIBUTED_DATA=1 THEN 'TOP 10%'
   WHEN DISTRIBUTED_DATA BETWEEN 2 AND 5 THEN 'MIDDLE 40%'
   ELSE "BOTTOM 50%"
END AS CATEGORY 
