-- MOST SPENDING CUSTOMERS
WITH total_spending as (
SELECT ACCOUNT_ID,SUM(AMOUNT_USD) AS TOTAL_AMOUNT,COUNT(TRANSACTION_ID) AS TOTAL_COUNT
FROM TRANSACTIONS 
GROUP BY ACCOUNT_ID),
AVG_DATA AS (SELECT AVG(TOTAL_AMOUNT) AS AVERAGE_AMOUNT,AVG(TOTAL_COUNT) AS AVERAGE_TRANSACTION FROM TOTAL_SPENDING)

SELECT T.ACCOUNT_ID,T.TOTAL_AMOUNT,T.TOTAL_COUNT FROM TOTAL_SPENDING T CROSS JOIN AVG_DATA A
WHERE T.TOTAL_AMOUNT>A.AVERAGE_AMOUNT AND T.TOTAL_COUNT>A.AVERAGE_TRANSACTION LIMIT 1;

-- SEGMENTING CUSTOMERS BASED ON TRANSACTION HISTORY
